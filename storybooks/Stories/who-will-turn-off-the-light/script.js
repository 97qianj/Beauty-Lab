function updatePreviewDots() {
  previewDots.forEach((dot, index) => dot.classList.toggle('active', index === previewIndex % previewDots.length));
}

function scrollPreview(direction) {
  if (!previewList) return;
  const items = [...previewList.querySelectorAll('img')];
  const visibleItems = 4;
  const maxIndex = Math.max(items.length - visibleItems, 0);
  previewIndex += direction;
  if (previewIndex > maxIndex) previewIndex = 0;
  if (previewIndex < 0) previewIndex = maxIndex;
  const target = items[previewIndex];
  previewList.scrollTo({ left: target?.offsetLeft || 0, behavior: 'smooth' });
  updatePreviewDots();
}

function restartPreviewTimer() {
  window.clearInterval(previewTimer);
  previewTimer = window.setInterval(() => scrollPreview(1), 3200);
}

