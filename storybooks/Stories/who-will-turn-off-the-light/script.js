window.addEventListener('keydown', (event) => {
  if (readingView.hidden) {
    if (event.key === 'Enter' || event.key === ' ') startReading(0);
    return;
  }
  if (event.key === 'ArrowLeft') goToPage(-1);
  if (event.key === 'ArrowRight') goToPage(1);
});

function restoreRouteFromUrl() {
  const pageIndex = pageIndexFromHash();
  if (pageIndex === null) {
    showCoverView();
    return;
  }
  startReading(pageIndex, { syncHash: false, playSound: false });
}

