function clampPageIndex(index) {
  return Math.min(Math.max(index, 0), pages.length - 1);
}

function pageIndexFromHash() {
  const match = window.location.hash.match(/^#read\/page-(\d+)$/);
  if (!match) return null;
  return clampPageIndex(Number(match[1]) - 1);
}

function updateReaderHash({ replace = true } = {}) {
  const nextHash = `#read/page-${currentPage + 1}`;
  if (window.location.hash !== nextHash) {
    const method = replace ? 'replaceState' : 'pushState';
    window.history[method](null, '', nextHash);
  }
}

function showCoverView() {
  coverView.hidden = false;
  readingView.hidden = true;
  document.body.classList.remove('is-reading');
}


function buildReaderNavigation() {
  if (readerProgress && !readerProgress.children.length) {
    pages.forEach((_, index) => {
      const dot = document.createElement('span');
      dot.dataset.page = String(index);
      readerProgress.append(dot);
    });
  }

  if (thumbnailList && !thumbnailList.children.length) {
    pages.forEach((page, index) => {
      const button = document.createElement('button');
      button.className = 'thumb-button';
      button.type = 'button';
      button.dataset.page = String(index);
      button.setAttribute('aria-label', `Go to page ${index + 1}`);

      const image = document.createElement('img');
      image.src = page.image;
      image.alt = '';

      const label = document.createElement('span');
      label.textContent = String(index + 1);

      button.append(image, label);
      button.addEventListener('click', () => goToPageNumber(index));
      thumbnailList.append(button);
    });
  }
}

function syncReaderNavigation() {
  readerProgress?.querySelectorAll('span').forEach((dot, index) => {
    dot.classList.toggle('active', index === currentPage);
  });

  thumbnailList?.querySelectorAll('.thumb-button').forEach((button, index) => {
    button.classList.toggle('active', index === currentPage);
    if (index === currentPage) {
      button.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
    }
  });
}

function scrollThumbnails(direction) {
  if (!thumbnailList) return;
  const amount = Math.max(thumbnailList.clientWidth * 0.72, 240);
  thumbnailList.scrollBy({ left: direction * amount, behavior: 'smooth' });
}

